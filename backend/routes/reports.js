const express = require('express');
const router = express.Router();
const { auth, requireRole } = require('../middleware/auth');
const PDFDocument = require('pdfkit');
const HealthRecord = require('../models/HealthRecord');
const User = require('../models/User');

router.get('/generate/:userId', auth, async (req, res) => {
  try {
    const user = await User.findById(req.params.userId).select('-password');
    if (!user) return res.status(404).json({ success: false, message: 'User not found' });

    const isOwner = req.user._id.toString() === user._id.toString();
    const isAssignedAsha = req.user.role === 'asha_worker' &&
      user.role === 'villager' &&
      user.assignedAshaWorker &&
      user.assignedAshaWorker.toString() === req.user._id.toString();
    if (!isOwner && !isAssignedAsha) {
      return res.status(403).json({ success: false, message: 'Access denied' });
    }

    const records = await HealthRecord.find({ userId: user._id }).sort({ visitDate: -1 }).limit(10);
    const safeName = String(user.name || 'patient').replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 60);
    const doc = new PDFDocument({ margin: 50 });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=health_report_${safeName}.pdf`);
    doc.pipe(res);

    doc.fontSize(24).fillColor('#2d6a4f').text('THE SAVIOUR', { align: 'center' });
    doc.fontSize(12).fillColor('#555').text('AI Smart Rural Health Assistant', { align: 'center' });
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke('#2d6a4f');
    doc.moveDown();
    doc.fontSize(16).fillColor('#1a1a2e').text('Patient Health Report');
    doc.moveDown(0.5);
    doc.fontSize(12).fillColor('#333');
    doc.text(`Name: ${user.name}`);
    doc.text(`Phone: ${user.phone}`);
    doc.text(`Age: ${user.age || 'N/A'} | Gender: ${user.gender || 'N/A'}`);
    doc.text(`Village: ${user.village || 'N/A'} | District: ${user.district || 'N/A'}`);
    doc.text(`Report Generated: ${new Date().toLocaleDateString('en-IN')}`);
    doc.moveDown();
    doc.fontSize(14).fillColor('#2d6a4f').text('Recent Health Records');
    doc.moveDown(0.5);

    if (records.length === 0) {
      doc.fontSize(12).fillColor('#555').text('No health records found.');
    } else {
      records.forEach((record, i) => {
        doc.fontSize(12).fillColor('#1a1a2e').text(`Visit ${i + 1}: ${new Date(record.visitDate).toLocaleDateString('en-IN')}`);
        if (record.symptoms?.length) doc.fontSize(10).fillColor('#555').text(`  Symptoms: ${record.symptoms.join(', ')}`);
        if (record.diagnosis) doc.fontSize(10).fillColor('#555').text(`  Diagnosis: ${record.diagnosis}`);
        if (record.temperature) doc.fontSize(10).fillColor('#555').text(`  Temperature: ${record.temperature}°F`);
        if (record.bloodPressure) doc.fontSize(10).fillColor('#555').text(`  Blood Pressure: ${record.bloodPressure}`);
        doc.moveDown(0.5);
      });
    }
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke('#ccc');
    doc.moveDown(0.5);
    doc.fontSize(9).fillColor('#888').text('This report is generated by The Saviour - AI Health Assistant. Consult a qualified doctor for medical advice.', { align: 'center' });
    doc.end();
  } catch (err) {
    console.error('Report generation failed:', err.message);
    if (!res.headersSent) res.status(500).json({ success: false, message: 'Failed to generate report' });
    else res.destroy(err);
  }
});

module.exports = router;
